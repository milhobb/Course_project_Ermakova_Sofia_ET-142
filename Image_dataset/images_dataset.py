# Импорт необходимых библиотек
import os
from PIL import Image
from collections import Counter
import matplotlib.pyplot as plt

# Загрузка папок с разметкой для построения диаграммы
from google.colab import drive
drive.mount('/content/drive')
train_path = "/content/drive/My Drive/labels_train"
test_path  = "/content/drive/My Drive/labels_test"

# Проверка размера изображений

# Загрузка папки test с изображениями для проверки качества
images_test  = "/content/drive/My Drive/images_test"

bad_files = []      # битые файлы
wrong_size = []     # не 600×600
sizes = []          # все размеры

# Проверка папки test
for folder in [images_test]:
    for filename in os.listdir(folder):
        if filename.endswith('.jpg'):
            filepath = os.path.join(folder, filename)
            try:
                with Image.open(filepath) as img:
                    img.verify()  # проверка на битость
                with Image.open(filepath) as img:
                    w, h = img.size
                    sizes.append((w, h))
                    if w != 600 or h != 600:
                        wrong_size.append((filename, w, h))
            except:
                bad_files.append(filename)

# Вывод
print("Проверка качества изображений")
print(f"Всего проверено: {len(sizes) + len(bad_files)}")
print(f"Битых файлов:    {len(bad_files)}")
print(f"Не 600×600:      {len(wrong_size)}")
print(f"Корректных:      {len(sizes) - len(wrong_size)}")

# Диаграмма «Распределение классов»

# Словарь классов
class_names = {0: 'helmet', 1: 'head'}
class_counts = Counter()

# Сбор статистики
for folder in [train_path, test_path]:
    for filename in os.listdir(folder):
        if filename.endswith('.txt'):
            with open(os.path.join(folder, filename)) as f:
                for line in f:
                    class_id = int(line.split()[0])
                    if class_id in class_names:
                        class_counts[class_names[class_id]] += 1

# Вывод
for name in ['head', 'helmet']:
    print(f"{name}: {class_counts.get(name, 0)}")

# Диаграмма
classes = ['head', 'helmet']
values = [class_counts.get(c, 0) for c in classes]
plt.bar(classes, values, color=['#FF9800', '#4CAF50'])
plt.title('Hard Hat Workers v3 — распределение классов')
plt.ylabel('Количество объектов')
plt.show()